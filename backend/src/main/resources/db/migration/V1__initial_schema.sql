CREATE TABLE countries (
    country_code CHAR(2) PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    currency_code CHAR(3) NOT NULL,
    CONSTRAINT ck_country_currency CHECK (
      (country_code = 'US' AND currency_code = 'USD') OR
      (country_code = 'IN' AND currency_code = 'INR') OR
      (country_code = 'GB' AND currency_code = 'GBP') OR
      (country_code = 'DE' AND currency_code = 'EUR') OR
      (country_code = 'CA' AND currency_code = 'CAD'))
);

CREATE TABLE departments (
    department_id UUID PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE employees (
    employee_id UUID PRIMARY KEY,
    employee_number VARCHAR(24) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL CHECK (length(trim(first_name)) > 0),
    last_name VARCHAR(80) NOT NULL CHECK (length(trim(last_name)) > 0),
    work_email VARCHAR(254) NOT NULL,
    hire_date DATE NOT NULL,
    country_code CHAR(2) NOT NULL REFERENCES countries(country_code),
    department_id UUID NOT NULL REFERENCES departments(department_id),
    job_title VARCHAR(100) NOT NULL CHECK (length(trim(job_title)) > 0),
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_employees_email_lower ON employees (lower(work_email));
CREATE INDEX ix_employees_active_number ON employees (archived_at, employee_number);
CREATE INDEX ix_employees_country ON employees (country_code);
CREATE INDEX ix_employees_department ON employees (department_id);
CREATE INDEX ix_employees_job_title ON employees (job_title);

CREATE TABLE salary_versions (
    salary_version_id UUID PRIMARY KEY,
    employee_id UUID NOT NULL REFERENCES employees(employee_id),
    effective_date DATE NOT NULL,
    currency_code CHAR(3) NOT NULL,
    basic_amount NUMERIC(14,2) NOT NULL CHECK (basic_amount >= 0),
    allowances_amount NUMERIC(14,2) NOT NULL CHECK (allowances_amount >= 0),
    deductions_amount NUMERIC(14,2) NOT NULL CHECK (deductions_amount >= 0),
    gross NUMERIC(14,2) GENERATED ALWAYS AS (basic_amount + allowances_amount) STORED,
    net NUMERIC(14,2) GENERATED ALWAYS AS (basic_amount + allowances_amount - deductions_amount) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (employee_id, effective_date),
    CHECK (net >= 0)
);
CREATE INDEX ix_salary_employee_effective ON salary_versions (employee_id, effective_date DESC);
CREATE INDEX ix_salary_insights ON salary_versions (currency_code, employee_id);

CREATE TABLE activity_log (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_identifier VARCHAR(100) NOT NULL,
    action VARCHAR(24) NOT NULL CHECK (action IN ('EMPLOYEE_CREATED','EMPLOYEE_UPDATED','EMPLOYEE_ARCHIVED','SALARY_CHANGED','IMPORT_CONFIRMED','EXPORT_CREATED')),
    employee_id UUID REFERENCES employees(employee_id) ON DELETE SET NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_activity_recent ON activity_log (occurred_at DESC, activity_id DESC);
CREATE INDEX ix_activity_employee_recent ON activity_log (employee_id, occurred_at DESC);

